#!/usr/bin/env node
// Builds assets/icons/sprite.svg from Phosphor Icons (@phosphor-icons/core).
// Add an icon name to ICONS (browse names at https://phosphoricons.com) and run `npm run icons`.
// Usage in HTML:  <svg class="icon" aria-hidden="true"><use href="assets/icons/sprite.svg#linkedin-logo"></use></svg>
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LIB = path.join(ROOT, 'node_modules/@phosphor-icons/core/assets');
const WEIGHT = 'regular';

const ICONS = [
  'linkedin-logo',
  'behance-logo',
  'spotify-logo',
  'medal',
  'newspaper-clipping',
  'arrow-up-right',
  'arrow-right',
  'arrow-up',
  'caret-up',
  'envelope-simple',
  'copy',
  'check',
];

const symbols = [];
for (const name of ICONS) {
  const file = path.join(LIB, WEIGHT, `${name}.svg`);
  const svg = await fs.readFile(file, 'utf8');
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  symbols.push(`<symbol id="${name}" viewBox="${viewBox}" fill="currentColor">${inner}</symbol>`);
}

const out = path.join(ROOT, 'assets/icons/sprite.svg');
await fs.mkdir(path.dirname(out), { recursive: true });
await fs.writeFile(
  out,
  `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Phosphor Icons (MIT) — generated by scripts/icons.mjs -->\n${symbols.join('\n')}\n</svg>\n`
);
console.log(`sprite.svg: ${ICONS.length} icons`);
